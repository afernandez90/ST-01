#pragma once
#include <stdint.h>

// Bits 0–6: segmentos A–G; bit 7: punto decimal.
// Las letras son aproximaciones de siete segmentos; no todos los glifos son únicos.
inline uint8_t mascaraDigito(uint8_t valor) {
  const uint8_t numeros[] = {0x3f,0x06,0x5b,0x4f,0x66,0x6d,0x7d,0x07,0x7f,0x6f};
  const uint8_t mayusculas[] = {
    0x77,0x7c,0x39,0x5e,0x79,0x71,0x3d,0x76,0x06,0x1e,0x75,0x38,0x37,
    0x54,0x3f,0x73,0x67,0x50,0x6d,0x78,0x3e,0x1c,0x2a,0x76,0x6e,0x5b
  };
  const uint8_t minusculas[] = {
    0x5f,0x7c,0x58,0x5e,0x7b,0x71,0x6f,0x74,0x04,0x0e,0x75,0x30,0x55,
    0x54,0x5c,0x73,0x67,0x50,0x6d,0x78,0x1c,0x1c,0x2a,0x76,0x6e,0x5b
  };
  if (!valor) return 0;
  if (valor<=9) return numeros[valor];
  if (valor==10) return numeros[0];
  if (valor<=20) return numeros[valor-11] | 0x80;
  if (valor<=27) return uint8_t(1)<<(valor-21);
  if (valor<=34) return (uint8_t(1)<<(valor-28)) | 0x80;
  if (valor<=60) return mayusculas[valor-35];
  if (valor<=86) return minusculas[valor-61];
  return 0;
}
